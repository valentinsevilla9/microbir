grant execute on function public.obtener_preguntas_de_fallos(uuid, integer) to authenticated;

revoke all on function public.obtener_asignaturas() from public;
grant execute on function public.obtener_asignaturas() to authenticated;

revoke all on function public.obtener_resumen_fallos(uuid) from public;
grant execute on function public.obtener_resumen_fallos(uuid) to authenticated;
